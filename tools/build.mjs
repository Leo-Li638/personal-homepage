// tools/build.mjs — 把 src/pages/*.page.html + src/partials/* 组装成站点根目录的 HTML 产物。
//
//   node tools/build.mjs            # 生成 index.html
//   node tools/build.mjs --check    # 只校验产物是否最新（不一致退出码 1）
//
// 指令（独占一行、顶格）：
//   <!-- @include: partials/header.html -->      路径相对 src/，禁止 .. 与绝对路径，禁止嵌套，禁止重复
//   {{AREA_SERVED}}                              JSON-LD 的 areaServed，由 assets/site-data.js 渲染
//
// 产物首行固定为 GENERATED banner；不要手改产物。
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { join, dirname, normalize, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'src');
const PAGES = join(SRC, 'pages');
const BANNER = '<!-- GENERATED by tools/build.mjs from src/pages/%PAGE% — DO NOT EDIT -->';
const INCLUDE_RE = /^<!-- @include: ([^>]+?) -->[ \t]*$/;

const args = process.argv.slice(2);
const CHECK = args.includes('--check');
const ONLY = (() => {
  const i = args.indexOf('--page');
  return i >= 0 && args[i + 1] ? args[i + 1] : null;
})();

function fail(msg) {
  console.error('BUILD FAIL: ' + msg);
  process.exit(1);
}

function loadSiteData() {
  const file = join(ROOT, 'assets', 'site-data.js');
  const sandbox = { window: {}, document: undefined };
  vm.createContext(sandbox);
  vm.runInContext(readFileSync(file, 'utf8'), sandbox, { filename: 'assets/site-data.js' });
  const SD = sandbox.window.SITE_DATA;
  if (!SD || !Array.isArray(SD.cities)) fail('assets/site-data.js 没有导出 window.SITE_DATA.cities');
  return SD;
}

// 展开 include：返回 { text, usedPartials }
function expand(pageFile) {
  const used = new Set();
  const pageRel = relative(SRC, pageFile).split(sep).join('/');
  const raw = readFileSync(pageFile, 'utf8');
  const out = [];
  // 保留原始换行：按行切但记住行尾（\r\n 或 \n）
  const lines = raw.split(/\r?\n/);
  for (const line of lines) {
    const m = INCLUDE_RE.exec(line);
    if (!m) { out.push(line); continue; }
    const rel = m[1].trim();
    if (rel.startsWith('/') || rel.includes('..')) fail(`${pageRel}: include 路径非法（禁止绝对路径与 ..）: ${rel}`);
    const abs = normalize(join(SRC, rel));
    if (!abs.startsWith(SRC + sep)) fail(`${pageRel}: include 越界: ${rel}`);
    if (!existsSync(abs)) fail(`${pageRel}: include 目标不存在: src/${rel}`);
    const key = rel.toLowerCase();
    if (used.has(key)) fail(`${pageRel}: partial 重复引用: ${rel}`);
    used.add(key);
    const body = readFileSync(abs, 'utf8').replace(/\r?\n$/, '');
    if (INCLUDE_RE.test(body) || /<!--\s*@include:/.test(body)) fail(`src/${rel}: partial 内禁止再 include（最多 1 层）`);
    for (const bl of body.split(/\r?\n/)) out.push(bl);
  }
  return { text: out.join('\n'), used };
}

function render(pageFile, SD) {
  const { text } = expand(pageFile);
  const areaServed = SD.cities.map(c => `{"@type":"City","name":"${c.zh}"}`).join(',');
  const body = text.replace(/\{\{AREA_SERVED\}\}/g, areaServed);
  if (/\{\{[A-Z_]+\}\}/.test(body)) {
    fail(`${relative(ROOT, pageFile)}: 未替换的占位符 ${body.match(/\{\{[A-Z_]+\}\}/)[0]}`);
  }
  const pageName = relative(SRC, pageFile).split(sep).join('/').split('/').pop();
  const banner = BANNER.replace('%PAGE%', pageName);
  // 产物第一行固定 banner，banner 之后保留原页面的换行风格（CRLF 工作区）
  return banner + '\r\n' + body.replace(/\r?\n/g, '\r\n');
}

const SD = loadSiteData();
const pages = readdirSync(PAGES).filter(f => f.endsWith('.page.html')).filter(f => !ONLY || f === ONLY);
if (!pages.length) fail(`src/pages 下没有 .page.html${ONLY ? `（--page ${ONLY}）` : ''}`);

let dirty = 0;
for (const f of pages) {
  const pageFile = join(PAGES, f);
  const outFile = join(ROOT, f.replace(/\.page\.html$/, '.html'));
  const want = render(pageFile, SD);
  const had = existsSync(outFile) ? readFileSync(outFile, 'utf8') : null;
  const name = relative(ROOT, outFile).split(sep).join('/');
  if (CHECK) {
    if (had === want) {
      console.log(`  ✓ ${name} 与源码一致`);
    } else {
      dirty++;
      console.log(`  ✗ ${name} 过期，请运行 node tools/build.mjs`);
    }
  } else if (had === want) {
    console.log(`  = ${name} 无变化`);
  } else {
    writeFileSync(outFile, want, 'utf8');
    console.log(`  ✓ ${name} 已生成（${Buffer.byteLength(want)} bytes）`);
  }
}

if (CHECK) {
  if (dirty) fail(`${dirty} 个产物与源码不一致`);
  console.log('BUILD CHECK OK');
} else {
  console.log('BUILD OK');
}

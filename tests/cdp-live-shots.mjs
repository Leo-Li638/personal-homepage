const targetId = t.result.targetId;
const at = await send('Target.attachToTarget', { targetId, flatten: true });
const S = (m, p) => send(m, p, at.result.sessionId);
const evl = async (expr) => { const r = await S('Runtime.evaluate', { expression: expr, returnByValue: true, awaitPromise: true }); return r.result && r.result.result ? r.result.result.value : undefined; };
await S('Page.enable'); await S('Runtime.enable');
await S('Emulation.setDeviceMetricsOverride', { width: 1366, height: 900, deviceScaleFactor: 1, mobile: false });
await S('Page.navigate', { url: 'https://xn--4gq.chat/' });
